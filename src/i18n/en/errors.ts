/** Names in quotes, with commas between them. */
const quoted = (names: string[]): string => names.map((n) => `"${n}"`).join(', ')

/** What a percentage is a percentage of, by the rule that sets it. */
const shareOf = (rule: RowRule | null): string =>
  rule === 'share-of-income' ? 'income' : rule === 'share-of-own-income' ? 'their own income' : rule === 'share-of-row' ? 'one income line' : 'what is left'

